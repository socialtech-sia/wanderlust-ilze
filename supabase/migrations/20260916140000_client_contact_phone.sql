-- Телефон клиента вместо номера разработчика.
--
-- В contact_phone стоял +371 20042830 — номер исполнителя, а не заказчика.
-- Он показывался на странице контактов, в подвале и подставлялся в
-- юридические тексты. contact_whatsapp держал тот же номер без пробелов,
-- поэтому меняются оба: починить один и оставить второй означало бы
-- оставить номер разработчика публично висеть на сайте.
--
-- Номер заказчика: +371 29299354.

update public.site_settings
   set value = '"+371 29299354"'::jsonb
 where key = 'contact_phone';

update public.site_settings
   set value = '"+37129299354"'::jsonb
